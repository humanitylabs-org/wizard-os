#!/usr/bin/env python3
"""Render Appearance v1 defaults deterministically; --check refuses asset drift."""
import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent
COLORS = {'canvas', 'base', 'chrome', 'overlay', 'surface', 'surface-raised', 'text', 'text-secondary', 'text-muted', 'border', 'accent', 'accent-soft', 'on-accent', 'reader-surface', 'panel', 'panel-raised'}
SKINS = ['nebula', 'grove', 'tide', 'ember', 'signal']


def render(data):
    assert data['schema'] == data['appearanceVersion'] == 1
    assert data['defaultSkin'] == 'nebula'
    assert list(data['skins']) == SKINS
    lines = ['/* Generated by style/generate_tokens.py from tokens.json. Do not edit. */']
    def block(selector, values):
        lines.append(selector + ' {')
        for name, value in values.items():
            assert isinstance(value, str) and not any(x in value for x in ';{}\n')
            lines.append(f'  --wz-{name}: {value};')
        lines.append('}')
    default = data['skins']['nebula']
    block(':root', {**data['roles'], **default['tokens']})
    lines.append(':root { color-scheme: dark; }')
    for name, skin in data['skins'].items():
        assert set(skin['tokens']) == COLORS
        assert skin['colorScheme'] == 'dark'
        # Repeat role defaults so switching back from Signal restores round controls.
        block(f'html[data-skin="{name}"]', {**data['roles'], **skin['roles'], **skin['tokens']})
    lines.append('html.wz-hosted, html[data-wz-hosted] { --wz-canvas: transparent; }')
    return '\n'.join(lines) + '\n'


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument('--check', action='store_true')
    args = ap.parse_args()
    expected = render(json.loads((ROOT / 'tokens.json').read_text()))
    target = ROOT / 'tokens.css'
    if args.check:
        if not target.exists() or target.read_text() != expected:
            raise SystemExit('DRIFT: run python3 style/generate_tokens.py')
        print('PASS: tokens.json and tokens.css match (Appearance v1, five skins).')
    else:
        target.write_text(expected)
        print('Generated style/tokens.css')


if __name__ == '__main__':
    main()
