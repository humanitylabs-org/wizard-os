#!/usr/bin/env python3
"""Generate reset-free shell control export + legacy skin bridge from the one kit.

The shell must not load ui.css's global resets or legacy alias block (it would
create --ink <-> --wz-text cycles). Apps still use the complete ui.css.
"""
from pathlib import Path
import argparse
import json
import re

ROOT = Path(__file__).resolve().parent
PREFIXES = ('.wz-button', '.wz-icon-button', '.wz-row', '.wz-main', '.wz-tile', '.wz-list', '.wz-pill', '.wz-field', '.wz-input')


def outputs():
    roles = json.loads((ROOT/'tokens.json').read_text())['roles']
    bridge = dict(roles)
    bridge.update({'base':'var(--bg)', 'canvas':'var(--bg)', 'text':'var(--ink)', 'text-secondary':'var(--ink-2)',
                   'text-muted':'var(--ink-3)', 'accent':'var(--violet-2)', 'on-accent':'var(--bg)',
                   'accent-soft':'color-mix(in srgb, var(--violet-2) 16%, transparent)', 'border':'var(--line-2)',
                   'surface':'color-mix(in srgb, var(--ink) 6%, transparent)',
                   'surface-raised':'color-mix(in srgb, var(--ink) 10%, transparent)',
                   'chrome':'var(--sk-win)', 'overlay':'var(--glass-2)',
                   'success':'var(--green)', 'warning':'var(--amber)', 'danger':'var(--red)'})
    tokens = '/* Generated by style/generate_shell.py; shell owns legacy skin variables. */\n:root {\n'
    tokens += ''.join(f'  --wz-{key}: {value};\n' for key,value in bridge.items())+'}\n'
    tokens += 'html[data-skin="signal"] { --wz-radius:2px; --wz-radius-tile:2px; --wz-radius-pill:2px; }\n'
    from generate_controls import generate
    return {'shell-tokens.css':tokens, 'controls.css':generate()}


if __name__=='__main__':
    ap=argparse.ArgumentParser(description=__doc__);ap.add_argument('--check',action='store_true');args=ap.parse_args()
    for name,content in outputs().items():
        if args.check:
            if not (ROOT/name).is_file() or (ROOT/name).read_text()!=content: ap.exit(1,name+' is stale\n')
        else: (ROOT/name).write_text(content)
    print('PASS: reset-free shell control export and skin bridge match canonical source.')
